#include <cstdio>

// Test function to print out a table of calculated values from 1.00Mhz -> 4.00Mhz,
// our target piece ID range
int main() {
  for (unsigned i = 300; i <= 1000; i += 50) {
    const uint32_t targetFreq = i * 10000;

    PllTccConfig best = getPllTccConfigForFreq(targetFreq);

    const uint32_t gclk = OscFreq / best.gclkDiv;
    // On PC only, calculate this more accurately (64 bit) instead of doing the PllDiv first
    const uint32_t pll = (uint64_t)gclk * (best.ldrWhole * LdrScalar + best.ldrFrac) / PllDiv / LdrScalar;
    const uint32_t tcc = pll / best.tccCnt;
    const float MHZ = 1'000'000;

    printf("%6.03fMHz:  GDiv: %3u  GClk: %6.03fMHz  LDR: %4u  FRAC: %2u  PLL: %6.03fMHz  TccCNT: %4u  Tcc: %5.03fMHz  Error: %+.07f\n",
        targetFreq / MHZ,
        best.gclkDiv,
        gclk / MHZ,
        best.ldrWhole - 1,
        best.ldrFrac,
        pll / MHZ,
        best.tccCnt,
        tcc / MHZ,
        (float)best.error / targetFreq);
  }
}
