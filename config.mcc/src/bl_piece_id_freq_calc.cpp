// The GClk used as the reference clock for the PLL is the 48Mhz
// internal osc divided by some prescalar
static const uint32_t OscFreq = 48'000'000;

// The hardware requires the PLL output to be 48Mhz-96Mhz
static const uint32_t PllMinFreq = 48'000'000;

// We choose a 4 as the divisor to allow more resolution in the multiplier
static const uint32_t PllDiv = 4;

// We are calculating LDR as a single integer that needs to be divided by
// 16 to get the real LDR register value and the 4-bit fractional part.
static const uint32_t LdrScalar = 16;

static constexpr unsigned getNextSmallestPowerOf2Shift(uint32_t val) {
  return (sizeof(val) * 8 - 1) - __builtin_clz(val);
}

static constexpr PllTccConfig calcConfigVals(uint32_t freq, uint8_t gclkDiv) {
  PllTccConfig config;

  const uint32_t gclk = (OscFreq / gclkDiv);

  // 48Mhz * 64 is very close to overflowing a 32-bit value (~2^31.5);
  // be careful if either of these parameters changes
  const uint32_t ldrMin = (PllMinFreq * LdrScalar * PllDiv + gclk - 1) / gclk;

  const uint8_t shift = getNextSmallestPowerOf2Shift(freq * LdrScalar * PllDiv / ldrMin);

  config.gclkDiv = gclkDiv;
  config.ldr = (freq * LdrScalar * PllDiv) >> shift;
  config.tccCnt = gclk >> shift;

  // Logically we would calculate PLL frequency as:
  //
  //    const uint32_t pllOut = gclk * config.ldr / PllDiv / LdrScalar;
  //
  // But gclk * ldr can overflow uint32_t by about 1.5x when PllDiv is 4:
  //
  //   ldrMax = PllMaxFreq * LdrScalar * PllDiv / gclk
  //
  //    96Mhz * LdrScalar * PllDiv * GClkDiv       48Mhz      
  //   -------------------------------------- *  ---------
  //                 48Mhz                        GClkDiv     
  //
  //   |----------- LDR Max ----------------|    |- GClk -|
  //
  //                        |  |  |                                                              
  //                        v  v  v                                                              
  //
  //         96 * LdrScalar
  //  Max = ---------------- * PllDiv * 48Mhz ~= 2^32.5
  //              48
  //
  // Divide gclk by PllDiv first to avoid overflow. This makes the max:
  //
  //      32 * 48Mhz ~= 2^30.5
  //
  // (LDR scales with PllDiv, so if PllDiv goes down, LDR will go down too and avoid the overflow)

  const uint32_t pllOut = (gclk / PllDiv) * config.ldr / 16;
  const uint32_t tccOut = pllOut / config.tccCnt;

  config.error = tccOut - freq;

  return config;
}

PllTccConfig constexpr getPllTccConfigForFreq(uint32_t targetFreq) {
  PllTccConfig best;

  uint32_t minError = std::numeric_limits<uint32_t>::max();

  // Scan through the available range of GClk values, calculating the
  // LDR and Tcc values for each and determining the resulting error
  // from the requested frequency.  Return the config with lowest error.
  FOR_DIV_VALUES(gclkDiv) {
    PllTccConfig config = calcConfigVals(targetFreq, gclkDiv);

    uint32_t posError = config.error < 0 ? -config.error : config.error;
    if (posError < minError) {
      minError = posError;
      best = config;
    }
  }

  return best;
}

