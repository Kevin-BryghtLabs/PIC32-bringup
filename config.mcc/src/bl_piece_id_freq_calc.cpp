// The frequency of the PLL output is
//
//   Fpll = Fref * (LDR + LDRFRAC/16) * 1 / (PSC)
//
// (The fact that LDR is specified as one less than the desired
//  multiplier and PSC is an exponent of 2 are ignored here and
//  treated as implementation details since they don't affect
//  the math)
//
// PSC can be 1, 2, or 4.  We choose 4, as a higher denominator
// allows higher resolution in the LDR value.  We also treat
// LDR as an integer value that needs to later be divided by
// 16 instead of a whole and fractional part.  This gives:
//
//                 LDR / 16      Fref * LDR
//  Fpll = Fref * ----------  = -------------
//                    4              64
//
// The hardware requires that the output of the PLL be between
// 48Mhz and 96Mhz, so:
//
//             Fref * LDR                 48Mhz * 64              96Mhz * 64
//   48Mhz <= ------------ <= 96Mhz  --> ------------ <= LDR <= -------------
//                 64                        Fref                    Fref    
//
// *** TODO: Update here for TCC mode (F vs F/2)
// The PID waveform is generated by the TCC driven by the PLL clock.
// Since the waveform updates when a TCC count is matched, the period
// time is:
//
//           Fpll
//  Ftcc = --------
//          TCCcnt
//
// Substituting the above values for Fpll, we get:
//
//         Fref * LDR
// Ftcc = -------------
//         64 * TCCcnt
//
// We are controlling the frequency by selecting LDR and TCCcnt, so solve
// for the ratio of those values:
//
//   LDR       Ftcc * 64
// -------- = -------------
//  TCCcnt       Fref
//
// Knowing the range requirements for LDR above, we can calculate a scalar
// to apply to move (Ftcc * 64) into the required range:
//
//                        Ftcc * 64
//  Shift = Floor( log2( ----------- ) )
//                         LDR Min
//
// (This can be done in hardware with CLZ)
//
// Our final values are then:
//
//   LDR    = (Ftcc * 64) >> Shift
//   TCCcnt = (Fref)      >> Shift
//
// For an example, If we want an output frequency of 1.4Mhz:
//   Shift = 15     ( 1.4MHz * 64 / 1536 = 0x0000E3DD, FFS = 15)
//
// LDR = (1.4Mhz * 64) >> 15 = 2734
// TCCcnt = (2Mhz) >> 15 = 61
//
// Plugging these values into the formula above shows that:
//
//                       Fref (2Mhz) * LDR (2734)
// Ftcc (1.400614Mhz) = --------------------------
//                           64 * TCCcnt (61)

// All primes from 2-255, which is about 20% of the size of 2-255.  This rarely
// picks the same values as the full scan, and increases the errors from around
// a thousandth of a percent to a hundredth of a percent. This is fine for our
// needs, but if there's an ideal smaller list to scan, primes don't seem to be it.
